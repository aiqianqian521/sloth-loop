"""Session isolation for the sloth_engine test package (cycle-40 A).

The plugin forward-tests materialise scratch packages under
``sloth_engine/tests/_tmp_*`` (gitignored). If a previous run leaves them on
disk, the plugin under test sees a store that already exists (`_ensure`
store-present path) instead of a blank one -- so the branch coverage drifted
between a clean clone (79.47%) and a warm checkout (79.48%) with no source
change. That is a test-conclusion drift, not a code defect.

Purging the scratch dirs at session start makes the recorded result identical
on a clean clone and on a warm machine. The scratch is regenerated by the
tests that need it; nothing tracked lives under ``_tmp_*``.
"""
from __future__ import annotations

import shutil
from pathlib import Path

import pytest

_HERE = Path(__file__).resolve().parent


@pytest.fixture(scope="session", autouse=True)
def _purge_tmp_scratch():
    """Remove ``_tmp_*`` scratch dirs left by earlier runs, before any test."""
    for d in _HERE.glob("_tmp_*"):
        if d.is_dir():
            shutil.rmtree(d, ignore_errors=True)
    yield
